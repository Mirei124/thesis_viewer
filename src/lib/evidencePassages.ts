import { isModelEligibleCandidate } from './evidencePacket';
import type { EvidenceCandidate, EvidenceLedger } from './evidenceLedger';

/** Bump when passage admission or joining rules change. */
export const EVIDENCE_PASSAGE_VERSION = 'local-evidence-passages-v1';

/**
 * A local-only trace for one original ledger item.  `text` is deliberately
 * not represented as an anchor or quote: a passage can span several real PDF
 * items and must never pretend to be one source quote.
 */
export type EvidencePassageMember = {
  candidate: EvidenceCandidate;
  textStart: number;
  textEnd: number;
};

export type EvidencePassage = {
  passageId: string;
  pageIndex: number;
  sectionTitle: string;
  /** Readable local context assembled from conservative adjacent PDF items. */
  text: string;
  /** Every original quote/anchor remains independently available here. */
  members: readonly EvidencePassageMember[];
  diagnostics: readonly string[];
};

export type EvidencePassageCollection = {
  version: typeof EVIDENCE_PASSAGE_VERSION;
  documentVersion: string;
  passages: readonly EvidencePassage[];
  diagnostics: readonly string[];
};

export type EvidencePassageOptions = {
  /** Target is diagnostic only; a passage may finish earlier at a safe boundary. */
  targetChars?: number;
  /** No passage text exceeds this bound. Long individual candidates are clipped transparently. */
  maxChars?: number;
  /** Avoid admitting isolated PDF.js fragments as model material. */
  minimumChars?: number;
};

const DEFAULT_TARGET_CHARS = 360;
const DEFAULT_MAX_CHARS = 960;
const DEFAULT_MINIMUM_CHARS = 56;

type CandidatePosition = { pageIndex: number; sourceOrder: number; ledgerOrder: number };

function positiveInteger(value: number | undefined, fallback: number, name: string): number {
  const result = value ?? fallback;
  if (!Number.isInteger(result) || result < 1) throw new Error(`${name} must be a positive integer.`);
  return result;
}

function positionForCandidate(candidate: EvidenceCandidate, ledgerOrder: number): CandidatePosition | undefined {
  // This coordinate is generated by the evidence ledger. A synthetic or old
  // candidate without it may remain a standalone passage, but is never merged.
  const match = /:p(\d+):i(\d+)$/.exec(candidate.evidenceId);
  return match ? { pageIndex: Number(match[1]), sourceOrder: Number(match[2]), ledgerOrder } : undefined;
}

function normalizedSectionTitle(candidate: EvidenceCandidate): string {
  return candidate.section.title.trim().replace(/\s+/g, ' ').toLocaleLowerCase();
}

function normalizedHeading(value: string): string {
  return value.trim().replace(/^(?:\d+(?:\.\d+)*\.?\s+)?/, '').replace(/[.:]+$/, '').replace(/\s+/g, ' ').toLocaleLowerCase();
}

function readableLength(text: string): number {
  return Array.from(text).filter((character) => /[\p{L}\p{N}]/u.test(character)).length;
}

function hasSentenceSignal(text: string): boolean {
  return /[.!?。！？]$/.test(text.trim()) || /\b(?:we|our|this|the|a|an|is|are|was|were|using|method|approach|model)\b/i.test(text);
}

function shouldKeep(text: string, memberCount: number, minimumChars: number): boolean {
  const readable = readableLength(text);
  return readable >= minimumChars || (memberCount >= 2 && readable >= Math.ceil(minimumChars * 0.75)) || (readable >= 32 && hasSentenceSignal(text));
}

/**
 * The shared packet rule rejects every short item. Here, a short item in an
 * already recognised body section may be retained *only* as a bridge to an
 * immediately adjacent item; `shouldKeep` still prevents it becoming a
 * standalone model passage. This lets PDF.js line fragments become prose
 * without reopening title-page/front-matter admission.
 */
function isJoinableBodyFragment(candidate: EvidenceCandidate): boolean {
  const text = candidate.quote.trim();
  const heading = normalizedHeading(text);
  return candidate.section.confidence === 'automatic'
    && readableLength(text) >= 3
    && normalizedHeading(candidate.section.title) !== heading
    && !/\b(?:doi|arxiv)\s*[:/]|https?:\/\/|\S+@\S+/i.test(text)
    && !/^[\p{P}\p{S}\d\s]+$/u.test(text);
}

function joinText(left: string, right: string): string {
  const previous = left.trimEnd();
  const next = right.trimStart();
  if (!previous) return next;
  if (!next) return previous;
  // The only destructive normalization is a conventional English line-break
  // hyphen followed by a lower-case continuation ("frame-" + "work").
  if (/[A-Za-z]-$/.test(previous) && /^[a-z]/.test(next)) return `${previous.slice(0, -1)}${next}`;
  // CJK prose normally has no inter-item space; preserve an existing boundary
  // for every other script so English words cannot run together.
  if (/[\p{Script=Han}\p{Script=Hiragana}\p{Script=Katakana}]/u.test(previous.at(-1)!)
    || /^[\p{Script=Han}\p{Script=Hiragana}\p{Script=Katakana}]/u.test(next)) return `${previous}${next}`;
  if (/^[,.;:!?，。；：！？)}\]]/.test(next)) return `${previous}${next}`;
  return `${previous} ${next}`;
}

function appendCandidate(
  text: string,
  members: EvidencePassageMember[],
  candidate: EvidenceCandidate,
  maxChars: number,
): { text: string; members: EvidencePassageMember[]; clipped: boolean } {
  const joined = joinText(text, candidate.quote);
  const available = Array.from(joined);
  const clipped = available.length > maxChars;
  const finalText = clipped ? `${available.slice(0, Math.max(0, maxChars - 1)).join('')}…` : joined;
  const start = text ? Math.min(text.length + (joined.length - text.trimEnd().length), finalText.length) : 0;
  // Character indices are only diagnostic; the candidate itself is the source
  // of truth for anchor resolution. Do not claim that a clipped suffix maps.
  const end = finalText.length;
  return { text: finalText, members: [...members, { candidate, textStart: start, textEnd: end }], clipped };
}

function canFollow(
  previous: EvidenceCandidate,
  candidate: EvidenceCandidate,
  previousPosition: CandidatePosition | undefined,
  position: CandidatePosition | undefined,
): boolean {
  return Boolean(previousPosition && position
    && previousPosition.pageIndex === position.pageIndex
    && position.sourceOrder === previousPosition.sourceOrder + 1
    && normalizedSectionTitle(previous) === normalizedSectionTitle(candidate));
}

/**
 * Builds cautiously readable passages while retaining a many-to-one mapping
 * back to immutable original evidence. This function never reads PDF blocks,
 * crosses pages/sections, or upgrades PDF.js source order into reading-order
 * certainty.
 */
export function createEvidencePassages(
  ledger: EvidenceLedger,
  options: EvidencePassageOptions = {},
): EvidencePassageCollection {
  const targetChars = positiveInteger(options.targetChars, DEFAULT_TARGET_CHARS, 'targetChars');
  const maxChars = positiveInteger(options.maxChars, DEFAULT_MAX_CHARS, 'maxChars');
  const minimumChars = positiveInteger(options.minimumChars, DEFAULT_MINIMUM_CHARS, 'minimumChars');
  if (targetChars > maxChars) throw new Error('targetChars cannot exceed maxChars.');

  const diagnostics: string[] = [];
  const passages: EvidencePassage[] = [];
  let text = '';
  let members: EvidencePassageMember[] = [];
  let firstPosition: CandidatePosition | undefined;
  let previous: EvidenceCandidate | undefined;
  let previousPosition: CandidatePosition | undefined;
  let clipped = false;

  const flush = () => {
    if (!previous || !members.length) return;
    if (shouldKeep(text, members.length, minimumChars)) {
      const position = firstPosition;
      passages.push({
        passageId: `${ledger.documentVersion}:${EVIDENCE_PASSAGE_VERSION}:p${position?.pageIndex ?? 'unknown'}:i${position?.sourceOrder ?? passages.length}`,
        pageIndex: position?.pageIndex ?? -1,
        sectionTitle: previous.section.title,
        text,
        members,
        diagnostics: [
          `${members.length} original PDF text item${members.length === 1 ? '' : 's'} retained as independently verifiable passage members.`,
          ...(clipped ? ['Passage text was bounded; its final original member remains available through its own anchor.'] : []),
        ],
      });
    } else {
      diagnostics.push(`Excluded an isolated ${readableLength(text)}-character PDF fragment from model-facing passages.`);
    }
    text = ''; members = []; firstPosition = undefined; previous = undefined; previousPosition = undefined; clipped = false;
  };

  for (const [ledgerOrder, candidate] of ledger.candidates.entries()) {
    if (candidate.coverage === 'unreadable' || (!isModelEligibleCandidate(candidate, ledger.candidates) && !isJoinableBodyFragment(candidate))) {
      diagnostics.push('Excluded a non-body, front-matter, heading, or unreadable ledger candidate.');
      flush();
      continue;
    }
    const position = positionForCandidate(candidate, ledgerOrder);
    const follows = previous && canFollow(previous, candidate, previousPosition, position);
    const prospective = follows ? joinText(text, candidate.quote) : candidate.quote.trim();
    // A target is a safe split point only after at least two real items. Never
    // split a single source solely because it is already substantial.
    if (!follows || (members.length >= 2 && Array.from(text).length >= targetChars) || Array.from(prospective).length > maxChars) flush();
    const added = appendCandidate(text, members, candidate, maxChars);
    text = added.text; members = added.members; clipped ||= added.clipped;
    if (!firstPosition) firstPosition = position;
    previous = candidate; previousPosition = position;
  }
  flush();

  diagnostics.unshift(`${passages.length} conservative local passage${passages.length === 1 ? '' : 's'} created from ${ledger.candidates.length} ledger candidate${ledger.candidates.length === 1 ? '' : 's'}.`);
  return { version: EVIDENCE_PASSAGE_VERSION, documentVersion: ledger.documentVersion, passages, diagnostics };
}
